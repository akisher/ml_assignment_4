# Feature Importance Plots
# -------------------------------------------------
def plot_feature_importance(model, feature_names, name):
    if hasattr(model, "feature_importances_"):
        importances = model.feature_importances_
        fi = pd.Series(importances, index=feature_names).sort_values(ascending=False)

        plt.figure(figsize=(10, 5))
        sns.barplot(x=fi.values, y=fi.index, palette="viridis")
        plt.title(f"Feature Importance - {name}")
        plt.xlabel("Importance Score")
        plt.ylabel("Feature")
        plt.show()

# Plot for each tree-based model
plot_feature_importance(dt.best_estimator_, data.feature_names, "Decision Tree")
plot_feature_importance(ada.best_estimator_, data.feature_names, "AdaBoost")
plot_feature_importance(gb.best_estimator_, data.feature_names, "Gradient Boosting")
plot_feature_importance(xgb_clf.best_estimator_, data.feature_names, "XGBoost")
plot_feature_importance(rf.best_estimator_, data.feature_names, "Random Forest")